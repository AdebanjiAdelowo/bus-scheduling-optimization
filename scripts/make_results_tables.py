"""Render every results table in docs/RESULTS_TABLES.md directly from results/*.csv.

Numbers in the documentation are produced by this script, not typed by hand.
Run: uv run python scripts/make_results_tables.py
"""

from __future__ import annotations

import json
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
RES, OUT = ROOT / "results", ROOT / "docs" / "RESULTS_TABLES.md"


def md(df: pd.DataFrame, nd: int = 3) -> str:
    df = df.copy()
    for c in df.columns:
        if pd.api.types.is_float_dtype(df[c]):
            df[c] = df[c].map(lambda v: "" if pd.isna(v) else f"{v:,.{nd}f}")
    cols = [str(c) for c in df.columns]
    lines = ["| " + " | ".join(cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    lines += ["| " + " | ".join(str(v) for v in row) + " |" for row in df.astype(object).to_numpy()]
    return "\n".join(lines)


def section(title: str, body: str) -> str:
    return f"## {title}\n\n{body}\n"


def main() -> None:
    parts = ["# Results tables\n\nGenerated by `scripts/make_results_tables.py` from `results/*.csv`. Do not edit by hand.\n"]

    f = pd.read_csv(RES / "forecast_metrics.csv")
    s = f[f.slice == "service_hours"]
    for metric in ("mae", "rmse", "wape", "bias"):
        t = s.pivot(index="model", columns="horizon_days", values=metric).sort_values(1).reset_index()
        t.columns = ["model"] + [f"{metric} h={h}d" for h in t.columns[1:]]
        parts.append(section(f"T1. Forecast {metric.upper()} on the test period, service hours", md(t)))
    t = f[(f.horizon_days == 1) & f.slice.isin(["weekday", "saturday", "sunday", "weekday_peak", "holiday"])]
    parts.append(section("T2. Day-ahead MAE by slice", md(t.pivot(index="model", columns="slice", values="mae").sort_values("weekday").reset_index(), 2)))

    d = pd.read_csv(RES / "policy_comparison_days.csv")
    g = d.groupby("policy").agg(model_wait=("model_mean_wait_min", "mean"), sim_wait=("sim_mean_wait_min", "mean"),
                                sim_p90=("sim_p90_wait_min", "mean"), sim_p95=("sim_p95_wait_min", "mean"),
                                within_10min=("sim_share_wait_le_10min", "mean"), unmet_share=("sim_unmet_share", "mean"),
                                overcrowded_pax_min=("sim_overcrowded_pax_min", "mean"), load_util=("sim_load_utilization", "mean"),
                                vehicle_hours=("vehicle_hours", "mean"), fleet_util=("fleet_utilization", "mean"),
                                cost_usd=("operating_cost_usd", "mean"), solve_s=("runtime_s", "mean")).sort_values("sim_wait").reset_index()
    parts.append(section(f"T3. Policy comparison, mean over {d.date.nunique()} held-out days", md(g)))
    sm = pd.read_csv(RES / "policy_comparison_summary.csv")
    for metric in ("model_mean_wait_min", "sim_mean_wait_min", "sim_p95_wait_min", "sim_overcrowded_pax_min"):
        t = sm[sm.metric == metric].drop(columns="metric").sort_values("pct_vs_baseline")
        parts.append(section(f"T4. Paired difference to the existing schedule: {metric}", md(t)))
    vh = pd.read_csv(RES / "policy_comparison_vs_milp_historical.csv")
    for metric in ("model_mean_wait_min", "sim_mean_wait_min"):
        parts.append(section(f"T5. Paired difference to the historical-demand MILP: {metric}",
                             md(vh[vh.metric == metric].drop(columns="metric").sort_values("pct_vs_baseline"), 4)))
    parts.append(section("T6. Simulated mean wait by day type", md(d.pivot_table(index="policy", columns="daytype", values="sim_mean_wait_min").reset_index())))
    parts.append(section("T7. Solver status over all policy-days", md(d.groupby(["policy", "status"]).size().rename("n").reset_index())))

    fr = pd.read_csv(RES / "resource_frontier.csv")
    for exp in ("budget_and_fleet", "fleet_only"):
        t = fr[fr.experiment == exp].pivot(index="scale", columns="policy", values="mean_wait_min")
        x = fr[(fr.experiment == exp) & (fr.policy == "milp")].set_index("scale")[["status", "vehicle_hours", "peak_fleet", "fleet_limit", "fleet_utilization"]]
        parts.append(section(f"T8. Resource sweep ({exp}): mean wait by policy, weekday planning model", md(t.join(x).reset_index())))
    ws = fr[fr.experiment == "weighted_sum"][["scale", "status", "mean_wait_min", "vehicle_hours", "peak_fleet", "operating_cost_usd", "verified"]]
    parts.append(section("T9. Weighted-sum formulation (lambda in passenger-minutes per vehicle-hour)", md(ws.rename(columns={"scale": "lambda"}))))
    if (RES / "infeasibility_check.csv").exists():
        parts.append(section("T10. Infeasible instances at low resource levels (weekday)", md(pd.read_csv(RES / "infeasibility_check.csv"), 1)))
    if (RES / "fleet_sensitivity_days.csv").exists():
        fl = pd.read_csv(RES / "fleet_sensitivity_days.csv")
        t = fl.groupby(["fleet_scale", "policy"])[["model_mean_wait_min", "sim_mean_wait_min", "sim_p95_wait_min", "vehicle_hours", "sim_overcrowded_pax_min"]].mean().reset_index()
        parts.append(section("T11. Fleet and budget scaling with day-ahead re-optimisation (15 test weekdays, simulation)", md(t)))

    if (RES / "demand_scaling_days.csv").exists():
        ds = pd.read_csv(RES / "demand_scaling_days.csv")
        for col, name in (("model_overload_pax", "passengers above the loading standard per day (planning formula, realised demand)"),
                          ("sim_overcrowded_pax_min", "overcrowded passenger-minutes per day (simulation)"),
                          ("sim_mean_wait_min", "simulated mean wait, minutes"), ("sim_unmet_capacity", "passengers never boarded for lack of capacity (simulation)"),
                          ("model_objective", "planning objective on realised demand, passenger-minutes")):
            nd = 0 if col in ("model_objective", "sim_unmet_capacity") else 2
            parts.append(section(f"T12. Demand scaling: {name}", md(ds.pivot_table(index="policy", columns="demand_scale", values=col).reset_index(), nd)))
        parts.append(section("T12b. Demand scaling: solver status and mean runtime",
                             md(ds.groupby(["policy", "status"]).agg(n=("runtime_s", "size"), mean_runtime_s=("runtime_s", "mean"), max_gap=("gap", "max")).reset_index(), 4)))

    if (RES / "stress_days.csv").exists():
        st = pd.read_csv(RES / "stress_days.csv")
        for col, name, nd in (("sim_mean_wait_min", "simulated mean wait, minutes", 3), ("sim_p95_wait_min", "simulated 95th percentile wait, minutes", 2),
                              ("sim_overcrowded_pax_min", "overcrowded passenger-minutes", 0), ("sim_unmet_capacity", "passengers never boarded for lack of capacity", 1),
                              ("delivered_trips_share", "share of planned trips delivered", 3)):
            parts.append(section(f"T13. Stress scenarios: {name}", md(st.pivot_table(index="policy", columns="scenario", values=col).reset_index(), nd)))

    if (RES / "scalability.csv").exists():
        sc = pd.read_csv(RES / "scalability.csv")
        cols = ["case", "routes", "method", "status", "objective", "bound", "gap", "runtime_s", "n_vars", "n_cons", "verified", "gap_to_best_exact"]
        parts.append(section("T14. Solver scaling and heuristic gaps", md(sc[[c for c in cols if c in sc.columns]], 5)))

    if (RES / "agent_eval_summary.csv").exists():
        parts.append(section("T15. Agent evaluation", md(pd.read_csv(RES / "agent_eval_summary.csv"))))
        status = RES / "agent_eval_llm_status.json"
        if status.exists():
            parts.append("LLM arm status: `" + json.dumps(json.loads(status.read_text())) + "`\n")

    OUT.write_text("\n".join(parts))
    print("wrote", OUT)


if __name__ == "__main__":
    main()
